FIX = Path(__file__).parent / "fixtures" / "rfb"


def _transport(version: str, calc: str, calls: list):
    def send(method, url, body, timeout):
        calls.append((method, url, body))
        name = version if method == "GET" else calc
        return (FIX / name).read_bytes(), {}
    return send


def test_live_simples_reply_parses_calculated_and_explained_not_calculated() -> None:
    calls: list = []
    client = RfbSimplesCalculatorClient(
        base_url="http://rtc-simples:8082/api",
        transport=_transport("sn_versao.json", "sn_calc.json", calls),
    )
    request = build_request(operation_id="ensaio-1", date="2027-03-10", document_type="55",
                            crt="1", items=[
                                SimplesItem(1, "000001", Decimal("1000.00"), c_ativ_sn="01",
                                            p_cbs_sn=Decimal("1.1612"),
                                            p_ibs_sn=Decimal("0.0129")),
                                SimplesItem(2, "000001", Decimal("50.00")),
                            ])
    result = client.calculate(request)
    assert result.component_version == "app=1.0.2;db=V0073"
    first, second = result.items
    assert first.state == "CALCULADO"
    assert first.values["vCBSSN"] == Decimal("11.61") and first.values["vIBSSN"] == Decimal("0.13")
    assert second.state == "NAO_CALCULADO" and "CATIVSN_AUSENTE" in second.error_codes
    with pytest.raises(RfbCalculationRejected):
        result.require_all_calculated()


def test_live_regime_regular_reply_flattens_ibscbs_and_flags_inconsistency() -> None:
    calls: list = []
    client = RfbRegimeRegularCalculatorClient(
        base_url="http://rtc-regime-regular:8080/api",
        transport=_transport("rr_versao.json", "rr_calc.json", calls),
    )
    request = build_rr_request(
        operation_id="ens-rr-1", occurred_at_iso="2026-11-20T10:00:00-03:00",
        municipality_ibge="3106200", state_code="MG", document_type=55, items=[
            RegimeRegularItem(1, "000", "000001", Decimal("1000.00"), ncm="84713012",
                              quantidade=Decimal("1"), unidade="UN"),
            RegimeRegularItem(2, "200", "200035", Decimal("80.00"), ncm="02013000"),
        ],
    )
    result = client.calculate(request)
    assert result.component_version == (
        f"app={REGIME_REGULAR_CALCULATOR_PIN.application_version};"
        f"db={CALCULATOR_DATABASE_VERSION}"
    )
    first, second = result.items
    assert first.values == {
        "vBC": Decimal("1000.00"), "vIBS": Decimal("1.00"), "vIBSUF": Decimal("1.00"),
        "vIBSMun": Decimal("0.00"), "vCBS": Decimal("9.00"),
    }
    assert second.state == "INCONSISTENCIA_ENTRADA" and second.error_codes == ("REG-011",)
    divergences = compare_regime_regular_shadow(result, {
        1: {"vBC": Decimal("1000.00"), "vIBS": Decimal("1.00"), "vCBS": Decimal("9.01")},
    })
    assert [(d.numero, d.field) for d in divergences] == [(1, "vCBS")]
    with pytest.raises(RfbCalculationRejected):
        result.require_all_computed()


