"""Adapter for the Receita Federal open-source Regime Regular RTC calculator.

RTC-RFB-06. Official component github.com/ReceitaFederal/
calculadora-rtc-regime-regular (MIT), pinned below and run as an INTERNAL
service, shadow only: NFCore remains the fiscal authority and never takes a
value from this reply into a document.

Contract read from the pinned source (1.7.2, 18/11/2026) and exercised against
a live instance with the V0073 database on 20/11/2026:
- POST /api/calculadora/observabilidade/regime-geral, one object per item with
  estadoItem in {CALCULADO, CALCULO_SIMULADO, NAO_IMPLEMENTADO,
  INCONSISTENCIA_ENTRADA, FALHA_TECNICA}; values nested under
  tribCalc.IBSCBS.gIBSCBS (vBC, gIBSUF.vIBSUF, gIBSMun.vIBSMun, vIBS, gCBS.vCBS).
- GET /api/calculadora/dados-abertos/versao -> versaoApp / versaoDb.
- aliquotasNominais are mandatory from 2027-01-01 and forbidden before.
"""
from __future__ import annotations

import json
import re
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from decimal import Decimal
from typing import Any

from .rfb_simples_calculator import (
    _DECIMAL_TEXT,
    RfbCalculationRejected,
    RfbCalculatorError,
    RfbComponentPin,
    ShadowDivergence,
    _find_version,
    _http,
    _internal_base_url,
    _money,
)

REGIME_REGULAR_CALCULATOR_PIN = RfbComponentPin(
    repository="https://github.com/ReceitaFederal/calculadora-rtc-regime-regular",
    commit="f1eebd7ce3157423b1a6aaca7dc1d6c3395452c4",
    application_version="1.7.2",
    license="MIT",
)
# Database generated by deploy/rfb/database from the same commit (Flyway).
CALCULATOR_DATABASE_VERSION = "V0073"
CALCULATE_PATH = "/calculadora/observabilidade/regime-geral"
VERSION_PATH = "/calculadora/dados-abertos/versao"
PAYLOAD_VERSION = "1.0.0"
_MAX_RESPONSE = 2 * 1024 * 1024
_STATES = frozenset({
    "CALCULADO", "CALCULO_SIMULADO", "NAO_IMPLEMENTADO",
    "INCONSISTENCIA_ENTRADA", "FALHA_TECNICA",
})
COMPUTED_STATES = frozenset({"CALCULADO", "CALCULO_SIMULADO"})
_DIGITS = re.compile(r"[0-9]+\Z")
_UF = re.compile(r"[A-Z]{2}\Z")


@dataclass(frozen=True, slots=True)
class RegimeRegularNominalRates:
    """Explicit reviewed nominal rates in percentage points, never assumed."""

    cbs: Decimal
    ibs_estadual: Decimal
    ibs_municipal: Decimal
    evidence_reference: str

    def as_payload(self) -> dict[str, str]:
        if not isinstance(self.evidence_reference, str) or not self.evidence_reference.strip():
            raise RfbCalculatorError("Reviewed nominal rate evidence required")
        values = {
            "cbs": self.cbs, "ibsEstadual": self.ibs_estadual,
            "ibsMunicipal": self.ibs_municipal,
        }
        result: dict[str, str] = {}
        for field, value in values.items():
            if (not isinstance(value, Decimal) or not value.is_finite()
                    or not Decimal("0") <= value <= Decimal("100")
                    or value != value.quantize(Decimal("0.0001"))):
                raise RfbCalculatorError("Nominal rate must be 0..100 with at most 4 decimals")
            result[field] = format(value.quantize(Decimal("0.0001")), "f")
        return result


@dataclass(frozen=True, slots=True)
class RegimeRegularItem:
    numero: int
    cst: str
    c_class_trib: str
    base_calculo: Decimal
    ncm: str | None = None
    nbs: str | None = None
    quantidade: Decimal | None = None
    unidade: str | None = None
    nominal_rates: RegimeRegularNominalRates | None = None

    def as_payload(self) -> dict[str, object]:
        if type(self.numero) is not int or not 1 <= self.numero <= 990:
            raise RfbCalculatorError("Item number must be 1..990")
        if not (_DIGITS.fullmatch(self.cst or "") and len(self.cst) == 3):
            raise RfbCalculatorError("CST must have 3 digits")
        if not (_DIGITS.fullmatch(self.c_class_trib or "") and len(self.c_class_trib) == 6):
            raise RfbCalculatorError("cClassTrib must have 6 digits")
        if (self.ncm is None) == (self.nbs is None):
            raise RfbCalculatorError("Exactly one of NCM (goods) or NBS (services) is required")
        payload: dict[str, object] = {
            "numero": self.numero, "cst": self.cst, "cClassTrib": self.c_class_trib,
            "baseCalculo": _money(self.base_calculo),
        }
        if self.ncm is not None:
            if not (_DIGITS.fullmatch(self.ncm) and len(self.ncm) == 8):
                raise RfbCalculatorError("NCM must have 8 digits")
            payload["ncm"] = self.ncm
        if self.nbs is not None:
            if not (_DIGITS.fullmatch(self.nbs) and len(self.nbs) == 9):
                raise RfbCalculatorError("NBS must have 9 digits")
            payload["nbs"] = self.nbs
        if self.quantidade is not None:
            payload["quantidade"] = str(self.quantidade)
        if self.unidade is not None:
            payload["unidade"] = self.unidade
        if self.nominal_rates is not None:
            payload["aliquotasNominais"] = self.nominal_rates.as_payload()
        return payload


def build_request(
    *, operation_id: str, occurred_at_iso: str, municipality_ibge: str, state_code: str,
    document_type: int, items: Sequence[RegimeRegularItem],
) -> dict[str, object]:
    if not isinstance(operation_id, str) or not 1 <= len(operation_id) <= 120:
        raise RfbCalculatorError("Operation id is required")
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:.]+[+-][0-9]{2}:[0-9]{2}",
                        occurred_at_iso or ""):
        raise RfbCalculatorError("dhFatoGerador must be ISO 8601 with offset")
    if occurred_at_iso[:4] >= "2027":
        if any(item.nominal_rates is None for item in items):
            raise RfbCalculatorError("Regime regular shadow from 2027 needs nominal rates")
    elif any(item.nominal_rates is not None for item in items):
        raise RfbCalculatorError("Nominal rates forbidden before 2027")
    if not (_DIGITS.fullmatch(municipality_ibge or "") and len(municipality_ibge) == 7):
        raise RfbCalculatorError("Municipality IBGE code must have 7 digits")
    if not _UF.fullmatch(state_code or ""):
        raise RfbCalculatorError("UF must be two upper-case letters")
    if document_type not in (55, 65, 91):
        raise RfbCalculatorError("Regime regular shadow covers NF-e, NFC-e and NFS-e")
    if not items or len({item.numero for item in items}) != len(items):
        raise RfbCalculatorError("Items must be present and uniquely numbered")
    return {
        "id": operation_id, "versao": PAYLOAD_VERSION, "dhFatoGerador": occurred_at_iso,
        "municipio": int(municipality_ibge), "uf": state_code, "tpDoc": document_type,
        "itens": [item.as_payload() for item in items],
    }


@dataclass(frozen=True, slots=True)
class RegimeRegularItemResult:
    numero: int
    state: str
    error_codes: tuple[str, ...]
    values: Mapping[str, Decimal]


@dataclass(frozen=True, slots=True)
class RegimeRegularCalculation:
    items: tuple[RegimeRegularItemResult, ...]
    component_version: str

    def require_all_computed(self) -> RegimeRegularCalculation:
        rejected = [
            (item.numero, item.state, item.error_codes)
            for item in self.items if item.state not in COMPUTED_STATES
        ]
        if rejected:
            raise RfbCalculationRejected(rejected)
        return self


def _amount(raw: object) -> Decimal | None:
    if isinstance(raw, str) and _DECIMAL_TEXT.fullmatch(raw):
        return Decimal(raw)
    if isinstance(raw, int | Decimal) and not isinstance(raw, bool):
        return Decimal(raw)
    return None


def _flatten(trib_calc: object) -> dict[str, Decimal]:
    """tribCalc.IBSCBS.gIBSCBS -> vBC, vIBSUF, vIBSMun, vIBS, vCBS."""
    if not isinstance(trib_calc, dict):
        return {}
    ibscbs = trib_calc.get("IBSCBS")
    group = ibscbs.get("gIBSCBS") if isinstance(ibscbs, dict) else None
    if not isinstance(group, dict):
        return {}
    picks = {
        "vBC": group.get("vBC"),
        "vIBS": group.get("vIBS"),
        "vIBSUF": (group.get("gIBSUF") or {}).get("vIBSUF"),
        "vIBSMun": (group.get("gIBSMun") or {}).get("vIBSMun"),
        "vCBS": (group.get("gCBS") or {}).get("vCBS"),
    }
    return {key: value for key, raw in picks.items() if (value := _amount(raw)) is not None}


def parse_response(
    raw: bytes, *, expected_items: Sequence[int], component_version: str,
) -> RegimeRegularCalculation:
    if not isinstance(raw, bytes) or not 0 < len(raw) <= _MAX_RESPONSE:
        raise RfbCalculatorError("Invalid official reply size")
    try:
        body = json.loads(raw, parse_float=Decimal)
    except (UnicodeDecodeError, ValueError):
        raise RfbCalculatorError("Official reply is not JSON") from None
    objects = body.get("objetos") if isinstance(body, dict) else None
    if not isinstance(objects, list):
        raise RfbCalculatorError("Official reply has no per-item results")
    results: list[RegimeRegularItemResult] = []
    for entry in objects:
        if not isinstance(entry, dict):
            raise RfbCalculatorError("Malformed official item")
        number, state = entry.get("nObj"), entry.get("estadoItem")
        if type(number) is not int or state not in _STATES:
            raise RfbCalculatorError("Official item lacks number or known state")
        errors = entry.get("erros") or []
        if not isinstance(errors, list):
            raise RfbCalculatorError("Malformed official item errors")
        codes = tuple(
            str(error["code"]) for error in errors
            if isinstance(error, dict) and isinstance(error.get("code"), str)
        )
        values = _flatten(entry.get("tribCalc"))
        if state in COMPUTED_STATES and "vCBS" not in values:
            raise RfbCalculatorError("Computed item without CBS value")
        results.append(RegimeRegularItemResult(number, str(state), codes, values))
    returned = [item.numero for item in results]
    if sorted(returned) != sorted(expected_items) or len(set(returned)) != len(returned):
        raise RfbCalculatorError("Official reply does not answer exactly the requested items")
    return RegimeRegularCalculation(
        tuple(sorted(results, key=lambda item: item.numero)), component_version,
    )


class RfbRegimeRegularCalculatorClient:
    def __init__(
        self, *, base_url: str, timeout_seconds: float = 10,
        pin: RfbComponentPin = REGIME_REGULAR_CALCULATOR_PIN,
        database_version: str = CALCULATOR_DATABASE_VERSION,
        transport: Callable[[str, str, bytes | None, float], tuple[bytes, Mapping[str, str]]]
        | None = None,
    ) -> None:
        if not 0 < timeout_seconds <= 30:
            raise ValueError("Invalid calculator timeout")
        self._base = _internal_base_url(base_url)
        self._timeout = timeout_seconds
        self._pin = pin
        self._database = database_version
        self._transport = transport or _http

    def verify_version(self) -> str:
        raw, _ = self._transport("GET", self._base + VERSION_PATH, None, self._timeout)
        try:
            body: Any = json.loads(raw)
        except (UnicodeDecodeError, ValueError):
            raise RfbCalculatorError("Calculator version reply is not JSON") from None
        app, database = _find_version(body)
        if app != self._pin.application_version:
            raise RfbCalculatorError(f"Calculator version {app!r} differs from the pin")
        if database != self._database:
            raise RfbCalculatorError(f"Calculator database {database!r} differs from the pin")
        return f"app={app};db={database}"

    def calculate(self, request: Mapping[str, object]) -> RegimeRegularCalculation:
        version = self.verify_version()
        items = request.get("itens")
        if not isinstance(items, list):
            raise RfbCalculatorError("Request has no items")
        expected = [int(item["numero"]) for item in items if isinstance(item, dict)]
        raw, _ = self._transport(
            "POST", self._base + CALCULATE_PATH,
            json.dumps(request, separators=(",", ":")).encode("utf-8"), self._timeout,
        )
        return parse_response(raw, expected_items=expected, component_version=version)


def compare_regime_regular_shadow(
    official: RegimeRegularCalculation, nfcore: Mapping[int, Mapping[str, Decimal]],
    *, fields: Sequence[str] = ("vBC", "vIBS", "vCBS"),
    tolerance: Decimal = Decimal("0.00"),
) -> tuple[ShadowDivergence, ...]:
    """Record differences only, for computed items; never changes a fiscal value."""
    divergences: list[ShadowDivergence] = []
    for item in official.items:
        if item.state not in COMPUTED_STATES:
            continue
        ours = nfcore.get(item.numero, {})
        for field in fields:
            a, b = ours.get(field), item.values.get(field)
            if a is None and b is None:
                continue
            if a is None or b is None or abs(a - b) > tolerance:
                divergences.append(ShadowDivergence(item.numero, field, a, b))
    return tuple(divergences)
